#!/usr/bin/env python3
"""Render a TrueType font into a TFT_eSPI smooth font (.vlw) as a C header.

TFT_eSPI's built-in fonts are ASCII only, so server answers in Russian came
out as garbage on the watch. This bakes Latin + Cyrillic glyphs into an
anti-aliased bitmap font that TFT_eSPI::loadFont(const uint8_t[]) reads from
flash.

VLW layout (all integers 32-bit big-endian), as read by TFT_eSPI's
Extensions/Smooth_font.cpp:
  header:  glyph count, version (11), font size, 0, ascent, descent
  metrics: per glyph: code point, height, width, x advance, dY (top of the
           bitmap above the baseline), dX (left offset), 0
  bitmaps: per glyph: width * height bytes of 8-bit alpha, rows top to bottom

The space character is not stored: TFT_eSPI draws it as a fixed gap.

Usage:
  tools/make_vlw_font.py --ttf /usr/share/fonts/truetype/dejavu/DejaVuSans.ttf \
      --size 18 --name ui_font_18 --out src/fonts/ui_font_18.h
"""

import argparse
import struct
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

# Printable ASCII, Latin-1 punctuation the gateway may use, Cyrillic (incl. Ё/ё
# and Ukrainian/Kazakh letters in U+0400..U+04FF), typographic quotes, dashes,
# ellipsis, degree, numero, arrows used in status texts.
DEFAULT_RANGES = [
    (0x21, 0x7E),
    (0xA0, 0xBF),
    (0xD7, 0xD7),
    (0x0400, 0x04FF),
    (0x2010, 0x2027),
    (0x2116, 0x2116),
    (0x2190, 0x2193),
]


def code_points(ranges):
    for first, last in ranges:
        yield from range(first, last + 1)


def render_glyph(font, cp):
    """Returns (bitmap bytes, width, height, x advance, dY, dX), or None for
    a glyph with no ink."""
    ch = chr(cp)
    left, top, right, bottom = font.getbbox(ch, anchor="ls")  # relative to the baseline
    width, height = right - left, bottom - top
    if width <= 0 or height <= 0:
        return None
    img = Image.new("L", (width, height), 0)
    ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255, anchor="ls")
    return img.tobytes(), width, height, round(font.getlength(ch)), -top, left


def build_vlw(font_path, size, ranges):
    font = ImageFont.truetype(str(font_path), size)
    ascent, descent = font.getmetrics()

    # Pillow renders a code point the TTF lacks as its .notdef box; U+FFFF is
    # never in a font, so its rendering is that box.
    notdef = render_glyph(font, 0xFFFF)
    glyphs = []
    for cp in code_points(ranges):
        rendered = render_glyph(font, cp)
        if rendered is None:
            continue
        if rendered == notdef:
            continue
        glyphs.append((cp,) + rendered)

    for cp, _bitmap, width, height, advance, dy, dx in glyphs:
        if not (0 < width < 256 and 0 < height < 256 and 0 <= advance < 256 and -128 <= dx < 128):
            sys.exit(f"glyph U+{cp:04X} does not fit TFT_eSPI's 8-bit metrics")

    out = bytearray()
    out += struct.pack(">6i", len(glyphs), 11, size, 0, ascent, descent)
    for cp, _bitmap, width, height, advance, dy, dx in glyphs:
        out += struct.pack(">7i", cp, height, width, advance, dy, dx, 0)
    for glyph in glyphs:
        out += glyph[1]
    return bytes(out), len(glyphs)


def write_header(path, name, data, glyph_count, source, size):
    lines = [
        f"// Generated by tools/make_vlw_font.py from {Path(source).name}, {size} px,",
        f"// {glyph_count} glyphs (Latin + Cyrillic). Do not edit by hand.",
        "#pragma once",
        "#include <pgmspace.h>",
        f"const uint8_t {name}[] PROGMEM = {{",
    ]
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ttf", required=True)
    ap.add_argument("--size", type=int, required=True, help="font size in pixels")
    ap.add_argument("--name", required=True, help="C array name")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    data, count = build_vlw(args.ttf, args.size, DEFAULT_RANGES)
    write_header(args.out, args.name, data, count, args.ttf, args.size)
    print(f"{args.out}: {count} glyphs, {len(data)} bytes")


if __name__ == "__main__":
    main()
